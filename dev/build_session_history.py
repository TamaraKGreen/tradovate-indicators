"""
Refresh the built-in session history inside Statmap_Session.js.

    python3 dev/build_session_history.py <1-minute bars file> [--keep 300]

The bars file is parquet or CSV with a timestamp column (`ts`, `timestamp` or `Date`+`Time`) and
open/high/low/close (any capitalisation). Timestamps that carry a timezone are converted to New York time;
naive ones are taken as New York local time. In the stats repo, for example:

    python3 -c "import sys; sys.path.insert(0,'.'); from research.scripts.load import load; load('all').to_parquet('/tmp/nq.parquet')"
    python3 dev/build_session_history.py /tmp/nq.parquet

Sessions are cut exactly as the indicator cuts them on a chart: a bar belongs to the session when its open time
(New York) falls in [start, end); a session runs from the first such bar to the last one before an out-of-session
bar; open = first bar's open, high/low = extremes, close = last bar's close. Only completed sessions are kept
(the one still running at the end of the file is dropped). The last `--keep` sessions per preset are written
between the BUILTIN-START / BUILTIN-END markers.
"""
import argparse
import json
import re
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
TARGET = HERE.parent / "Statmap_Session.js"
NY = "America/New_York"
# must match SESS in Statmap_Session.js
PRESETS = {"rth": (570, 960), "fut": (480, 1020), "lon": (120, 480), "asia": (1140, 120), "mid": (0, 1020), "day": (1080, 960)}


def read_bars(path):
    path = Path(path)
    d = pd.read_parquet(path) if path.suffix in (".parquet", ".pq") else pd.read_csv(path)
    cols = {c.lower(): c for c in d.columns}
    if "ts" in cols or "timestamp" in cols:
        ts = pd.to_datetime(d[cols.get("ts", cols.get("timestamp"))])
    else:
        ts = pd.to_datetime(d[cols["date"]].astype(str) + " " + d[cols["time"]].astype(str))
    ts = ts.dt.tz_convert(NY) if ts.dt.tz is not None else ts.dt.tz_localize(NY, ambiguous=True, nonexistent="shift_forward")
    out = pd.DataFrame({"ts": ts, **{k: d[cols[k]].astype(float) for k in ("open", "high", "low", "close")}})
    return out.sort_values("ts").drop_duplicates("ts").reset_index(drop=True)


def sessions(b, a, e):
    mod = b.ts.dt.hour * 60 + b.ts.dt.minute
    ins = (mod >= a) & (mod < e) if a < e else (mod >= a) | (mod < e)
    start = ins & ~ins.shift(1, fill_value=False)
    run = start.cumsum().where(ins)
    g = b[ins].groupby(run[ins])
    s = pd.DataFrame({"t": g.ts.first(), "o": g.open.first(), "h": g.high.max(), "l": g.low.min(), "c": g.close.last()})
    if len(s) and ins.iloc[0] and mod.iloc[0] != a:          # file starts mid-session: wrong open, as the indicator does
        s = s.iloc[1:]
    if len(s) and ins.iloc[-1]:                               # still running at the end of the file
        s = s.iloc[:-1]
    return s


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("bars")
    ap.add_argument("--keep", type=int, default=300)
    ap.add_argument("--target", default=str(TARGET), help="indicator file to update (default: Statmap_Session.js)")
    a = ap.parse_args()
    target = Path(a.target)
    b = read_bars(a.bars)
    blob, asof = {}, b.ts.iloc[-1].strftime("%Y-%m-%d %H:%M")
    for key, (st, en) in PRESETS.items():
        s = sessions(b, st, en).tail(a.keep)
        blob[key] = [[int(t.value // 60_000_000_000), o, h, l, c] for t, o, h, l, c in s.itertuples(index=False)]
        print(f"{key:5s} {len(s):4d} sessions  {s.t.iloc[0]:%Y-%m-%d %H:%M} -> {s.t.iloc[-1]:%Y-%m-%d %H:%M}")
    body = ("const BUILTIN = { asof: " + json.dumps(asof) + ", sessions: {\n" +
            ",\n".join(f"    {k}: " + json.dumps(v, separators=(",", ":")) for k, v in blob.items()) + "\n} };")
    src = target.read_text()
    new, n = re.subn(r"// BUILTIN-START.*?// BUILTIN-END", lambda _: "// BUILTIN-START (generated by dev/build_session_history.py - do not edit by hand)\n" + body + "\n// BUILTIN-END", src, flags=re.S)
    if n != 1:
        raise SystemExit("BUILTIN-START / BUILTIN-END markers not found in Statmap_Session.js")
    target.write_text(new)
    print(f"wrote {target.name}: history to {asof} NY, {target.stat().st_size / 1e3:.0f} KB")


if __name__ == "__main__":
    main()
